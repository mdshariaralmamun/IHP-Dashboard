def test_preview_returns_the_document(client, admin_headers, mom_project):
    pid = mom_project["id"]
    body = _preview(client, admin_headers, pid)
    expected = _code(mom_project["pr_number"], body["version"])
    assert body["document_code"] == expected
    assert body["revision"] == f"R{body['version'] - 1:02d}"
    # the file name and the document header use the same code
    assert expected in body["html"]
    assert body["html"].startswith("<!DOCTYPE html") or "<html" in body["html"]
    assert "Please review and confirm the accuracy of this document." in body["html"]
    assert "Generated by IHP Project Delivery Platform" in body["html"]
    assert mom_project["title"] in body["html"]
    assert body["bytes"] == len(body["html"])


def test_preview_equals_the_web_view(client, admin_headers, mom_project):
    """One source of truth: the preview and the printable page are the same string."""
    pid = mom_project["id"]
    preview = _preview(client, admin_headers, pid)
    view = client.get(f"/api/projects/{pid}/mom/view", headers=admin_headers)
    assert view.status_code == 200
    assert view.text == preview["html"]


def test_patch_creates_the_record_and_the_preview_then_works(client, admin_headers, project):
    """A project with no MOM yet: the first autosave creates the draft record."""
    pid = project["id"]
    resp = client.patch(
        f"/api/projects/{pid}/mom",
        json={"meeting_title": "First autosave"},
        headers=admin_headers,
    )
    assert resp.status_code == 200, resp.text
    assert resp.json()["version"] == 1
    db = SessionLocal()
    mom = db.query(MomRecord).filter(MomRecord.project_id == pid).first()
    assert mom is not None and mom.docx_filename == ""
    db.close()
    assert "First autosave" in _preview(client, admin_headers, pid)["html"]


