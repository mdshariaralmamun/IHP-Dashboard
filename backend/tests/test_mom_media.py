def test_immediate_flush_then_read_back(client, admin_headers, project):
    """What the blur / pagehide flush sends: one immediate PATCH, nothing debounced
    on the server, durable the moment it arrives - and the last write wins."""
    pid = project["id"]
    first = client.patch(
        f"/api/projects/{pid}/mom",
        json={"meeting_title": "typed then refreshed"},
        headers=admin_headers,
    )
    assert first.status_code == 200
    assert "typed then refreshed" in _preview(client, admin_headers, pid)["html"]

    second = client.patch(
        f"/api/projects/{pid}/mom", json={"meeting_title": "second edit"}, headers=admin_headers
    )
    assert second.status_code == 200
    html = _preview(client, admin_headers, pid)["html"]
    assert "second edit" in html and "typed then refreshed" not in html


