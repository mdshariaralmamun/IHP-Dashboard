def test_patch_persists_and_never_regenerates(client, admin_headers, mom_project):
    pid = mom_project["id"]
    db = SessionLocal()
    before = db.query(MomRecord).filter(MomRecord.project_id == pid).first()
    version, docx_name = before.version, before.docx_filename
    db.close()

    payload = {
        "meeting_title": "Gas line site meeting",
        "meeting_location": "B5 - Room 5-3201",
        "meeting_date": "2026-10-14",
        "meeting_time": "10:00-11:30",
        "attendees": [{"name": "A. Rehman", "title": "PI", "email": "pi@example.kaust.edu.sa"}],
        "agenda": [{"scope": "Install the gas line", "action": "IHP", "etc": "2 weeks"}],
    }
    resp = client.patch(f"/api/projects/{pid}/mom", json=payload, headers=admin_headers)
    assert resp.status_code == 200, resp.text
    stored = resp.json()["details"]
    for key, value in payload.items():
        assert stored[key] == value

    db = SessionLocal()
    after = db.query(MomRecord).filter(MomRecord.project_id == pid).first()
    assert after.version == version                      # never regenerated
    assert after.docx_filename == docx_name              # the document is untouched
    assert after.details["meeting_title"] == "Gas line site meeting"
    db.close()

    audit = client.get(f"/api/projects/{pid}/audit", headers=admin_headers)
    assert "mom:edit" in str(audit.json())


