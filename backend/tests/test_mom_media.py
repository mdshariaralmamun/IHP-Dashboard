    assert "wordprocessingml" in resp.headers["content-type"]
    assert code + ".docx" in resp.headers["content-disposition"]
    assert len(resp.content) > 2000
    db = SessionLocal()
    row = (
        db.query(Attachment)
        .filter(Attachment.project_id == pid, Attachment.filename == code + ".docx")
        .first()
    )
    assert row is not None and row.stage == "DELIVERABLE"
    db.close()


