def test_export_pdf_is_named_attached_and_printed_from_the_preview(
    client, admin_headers, mom_project, monkeypatch
):
    captured: dict = {}

    def fake_html_to_pdf(html, out_path, *, base_url=""):
        captured["html"] = html
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_bytes(b"%PDF-1.4\n% fake for the test\n%%EOF\n")
        return out_path

    monkeypatch.setattr(docgen, "html_to_pdf", fake_html_to_pdf)
    pid = mom_project["id"]
    code = _code(mom_project["pr_number"], _version(pid))
    resp = client.get(f"/api/projects/{pid}/mom/export?format=pdf", headers=admin_headers)
    assert resp.status_code == 200, resp.text
    assert resp.headers["content-type"] == "application/pdf"
    assert code + ".pdf" in resp.headers["content-disposition"]

    # the same HTML that the preview serves was handed to the renderer
    assert captured["html"] == _preview(client, admin_headers, pid)["html"]

    db = SessionLocal()
    row = (
        db.query(Attachment)
        .filter(Attachment.project_id == pid, Attachment.filename == code + ".pdf")
        .first()
    )
    assert row is not None
    assert row.stage == "DELIVERABLE"
    assert row.content_type == "application/pdf"
    db.close()
    assert "mom:export" in str(
        client.get(f"/api/projects/{pid}/audit", headers=admin_headers).json()
    )


