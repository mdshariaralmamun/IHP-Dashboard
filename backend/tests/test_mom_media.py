def test_email_draft_content(client, admin_headers, mom_project):
    pid = mom_project["id"]
    resp = client.get(f"/api/projects/{pid}/mom/email-draft", headers=admin_headers)
    assert resp.status_code == 200, resp.text
    draft = resp.json()
    code = _code(mom_project["pr_number"], _version(pid))
    assert code in draft["subject"]
    assert draft["cc"] == ["IHP.design@kaust.edu.sa"]
    assert "Please review and confirm the accuracy of this document." in draft["body"]
    assert mom_project["pr_number"] in draft["body"]
    assert draft["attachment"]["filename"] == code + ".pdf"
    assert draft["attachment"]["download_url"].endswith("/mom/export?format=pdf")
    assert draft["attachment_supported"] is False
    assert "mailto" in draft["path_taken"]


def test_email_draft_409_without_any_email(client, admin_headers):
    data = _make_project(client, admin_headers, email=None)
    try:
        pid = data["id"]
        resp = client.patch(
            f"/api/projects/{pid}/mom",
            json={"attendees": [{"name": "No Address", "title": "PI", "email": ""}]},
            headers=admin_headers,
        )
        assert resp.status_code == 200
        draft = client.get(f"/api/projects/{pid}/mom/email-draft", headers=admin_headers)
        assert draft.status_code == 409, draft.text
        assert "No attendee emails and no project contact" in draft.text
    finally:
        _cleanup(data["id"])


def test_email_draft_dedupes_cc_against_to(client, admin_headers, monkeypatch):
    """The design mailbox is copied in, but never twice."""
    data = _make_project(client, admin_headers)
    try:
        pid = data["id"]
        # the design mailbox is one of the attendees: Cc must come back empty
        resp = client.patch(
            f"/api/projects/{pid}/mom",
            json={"attendees": [
                {"name": "In-House Projects Design", "title": "IHP",
                 "email": "IHP.design@kaust.edu.sa"},
                {"name": "A. Rehman", "title": "PI", "email": "pi@example.kaust.edu.sa"},
            ]},
            headers=admin_headers,
        )
        assert resp.status_code == 200, resp.text
        draft = client.get(f"/api/projects/{pid}/mom/email-draft", headers=admin_headers).json()
        assert "ihp.design@kaust.edu.sa" in [e.lower() for e in draft["to"]]
        assert draft["cc"] == []

        # an attendee list without the design mailbox still copies it in
        resp = client.patch(
            f"/api/projects/{pid}/mom",
            json={"attendees": [{"name": "A. Rehman", "title": "PI",
                                 "email": "pi@example.kaust.edu.sa"}]},
            headers=admin_headers,
        )
        assert resp.status_code == 200
        draft = client.get(f"/api/projects/{pid}/mom/email-draft", headers=admin_headers).json()
        assert draft["cc"] == ["IHP.design@kaust.edu.sa"]
    finally:
        _cleanup(data["id"])
