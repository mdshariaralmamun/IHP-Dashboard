def test_email_eml_attachment_is_the_export_bytes(client, admin_headers, mom_project, monkeypatch):
    """One source of truth: the attachment IS the export file."""
    payload = b"%PDF-1.4\n% one source of truth\n%%EOF\n"
    monkeypatch.setattr(docgen, "html_to_pdf", _fake_pdf(payload))
    pid = mom_project["id"]
    eml = client.get(f"/api/projects/{pid}/mom/email.eml", headers=admin_headers)
    assert eml.status_code == 200, eml.text
    message = email.message_from_bytes(eml.content)
    parts = [part for part in message.walk() if part.get_filename()]
    attached = parts[0].get_payload(decode=True)
    exported = client.get(f"/api/projects/{pid}/mom/export?format=pdf", headers=admin_headers)
    assert exported.status_code == 200
    assert attached == exported.content == payload
    audit = str(client.get(f"/api/projects/{pid}/audit", headers=admin_headers).json())
    assert "mom:eml" in audit


FOOTER_NEW = "Please review this document and reply with your comments or approval."
FOOTER_OLD = "Please review and confirm the accuracy of this document."


def test_mom_footer_sentence_everywhere(client, admin_headers, mom_project, monkeypatch):
    """One sentence, every surface: preview/view HTML, the PDF source, the .eml and the Word."""
    captured: dict = {}

    def _capture(html, out_path, *, base_url=""):
        captured["html"] = html
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_bytes(b"%PDF-1.4\n% footer check\n%%EOF\n")
        return out_path

    monkeypatch.setattr(docgen, "html_to_pdf", _capture)
    pid = mom_project["id"]

    # 1. the HTML preview and the web view (still one source of truth)
    preview = client.get(f"/api/projects/{pid}/mom/preview", headers=admin_headers).json()
    view = client.get(f"/api/projects/{pid}/mom/view", headers=admin_headers)
    assert view.text == preview["html"]
    assert FOOTER_NEW in preview["html"] and FOOTER_OLD not in preview["html"]

    # 2. the PDF is printed from exactly that HTML, so the sentence is in it
    pdf = client.get(f"/api/projects/{pid}/mom/export?format=pdf", headers=admin_headers)
    assert pdf.status_code == 200, pdf.text
    assert FOOTER_NEW in captured["html"] and FOOTER_OLD not in captured["html"]

    # 3. the .eml carries that same PDF, byte for byte
    eml = client.get(f"/api/projects/{pid}/mom/email.eml", headers=admin_headers)
    assert eml.status_code == 200, eml.text
    message = email.message_from_bytes(eml.content)
    attached = [p for p in message.walk() if p.get_filename()][0].get_payload(decode=True)
    assert attached == pdf.content

    # 4. the Word minute: the template plus the shared footer lines
    docx = client.get(f"/api/projects/{pid}/mom/export?format=docx", headers=admin_headers)
    assert docx.status_code == 200, docx.text
    from io import BytesIO

    from docx import Document as DocxDocument

    document = DocxDocument(BytesIO(docx.content))
    text = "\n".join(paragraph.text for paragraph in document.paragraphs)
    assert FOOTER_NEW in text
    assert FOOTER_OLD not in text
    assert mom_html.MOM_FOOTER_META.format(
        generated_at=mom_html.generated_at(mom_project["pr_number"])
    ) in text
