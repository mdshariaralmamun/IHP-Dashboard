"""The MOM panel's live preview, named exports, email draft and autosave.

The preview must be the same HTML the PDF is printed from (one source of truth),
the exports must be named and filed on the PR as DELIVERABLE attachments, and the
autosave must persist an immediate PATCH - which is what the browser's blur /
pagehide flush sends.
"""

import uuid

import pytest

from app.db import SessionLocal
from app.models import Attachment, AuditLog, MomRecord, Project
from app.services import docgen


def _cleanup(project_id: int) -> None:
    db = SessionLocal()
    try:
        for model in (Attachment, MomRecord):
            db.query(model).filter(model.project_id == project_id).delete()
        db.query(AuditLog).filter(AuditLog.project_id == project_id).delete()
        db.query(Project).filter(Project.id == project_id).delete()
        db.commit()
    finally:
        db.close()


def _make_project(client, admin_headers, *, email="pi@example.kaust.edu.sa"):
    pr = "PR-MOM-" + uuid.uuid4().hex[:6].upper()
    resp = client.post(
        "/api/projects",
        json={
            "pr_number": pr,
            "title": "MOM media check",
            "description": "Type: BASELINE\nDivision: PSE",
            "pi_name": "Dr. Example",
            "pi_email": email,
        },
        headers=admin_headers,
    )
    assert resp.status_code == 201, resp.text
    return resp.json()


@pytest.fixture()
def project(client, admin_headers):
    data = _make_project(client, admin_headers)
    yield data
    _cleanup(data["id"])


@pytest.fixture()
def mom_project(client, admin_headers, project):
    """The same project with a MOM already generated (so docx_filename exists)."""
    resp = client.post(f"/api/projects/{project['id']}/mom/generate", headers=admin_headers)
    assert resp.status_code == 200, resp.text
    return project


def _version(project_id: int) -> int:
    db = SessionLocal()
    try:
        mom = db.query(MomRecord).filter(MomRecord.project_id == project_id).first()
        return mom.version if mom else 0
    finally:
        db.close()


def _code(pr_number: str, version: int) -> str:
    """The record's own document code: IHP-MOM-{pr}-R{version-1:02d}."""
    return "IHP-MOM-" + pr_number + "-R" + f"{version - 1:02d}"


def _preview(client, headers, pid):
    resp = client.get(f"/api/projects/{pid}/mom/preview", headers=headers)
    assert resp.status_code == 200, resp.text
    return resp.json()


# ---------------------------------------------------------------------------
# 1-3  preview
